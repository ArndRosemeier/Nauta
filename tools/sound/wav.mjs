/**
 * What the synthesised takes share (pipe.mjs, ring.mjs): the game's sample rate, a seeded random stream and a mono
 * 16-bit WAV writer, so the shared make script levels and encodes a synthesised take like every other.
 */

/** Sample rate, Hz (the game's: the make script keeps it). */
export const RATE = 32000;

/** A seeded stream of numbers in [0, 1) (xorshift). */
export function rng(seed) {
  let s = seed >>> 0 || 1;
  return () => { s ^= s << 13; s >>>= 0; s ^= s >>> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; };
}

/** Mono samples (-1..1) at RATE as a 16-bit WAV file's bytes. */
export function wav(samples) {
  const data = Buffer.alloc(samples.length * 2);
  samples.forEach((v, i) => data.writeInt16LE(Math.round(Math.max(-1, Math.min(1, v)) * 32767), i * 2));
  const h = Buffer.alloc(44);
  h.write('RIFF', 0); h.writeUInt32LE(36 + data.length, 4); h.write('WAVE', 8); h.write('fmt ', 12);
  h.writeUInt32LE(16, 16); h.writeUInt16LE(1, 20); h.writeUInt16LE(1, 22); h.writeUInt32LE(RATE, 24);
  h.writeUInt32LE(RATE * 2, 28); h.writeUInt16LE(2, 32); h.writeUInt16LE(16, 34); h.write('data', 36); h.writeUInt32LE(data.length, 40);
  return Buffer.concat([h, data]);
}
